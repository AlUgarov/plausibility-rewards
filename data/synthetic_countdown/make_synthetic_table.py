"""../../tables/tab_synthetic_countdown.tex: synthetic gaming tests on Countdown. results.csv, edits.csv, scores.csv from
Consistency_Synthetic_Gaming_Countdown (Drive countdown/sft/<mixed SFT>/synthetic_gaming_seed0/): per puzzle a
checker-verified gold solution and 8 edits of it, scored under the judge prompt; gold_wins = share of puzzles with the
gold solution scored above the edit (ties 1/2). The table: base model, SFT policy, corrupt DPO judge; every score, in
the notebook printout's order (low10, mean, min, sc, sum); the solver and SimPO judges and shift_in_gaps are in
results.csv. Scaled to the text width (adjustbox); notes as a minipage (threeparttable can't measure an adjustbox)."""
import pandas as pd

JUDGES = [("base", "Base model"), ("sft", "SFT policy"), ("corrupt", "Corrupt DPO")]
SCORES = [("low10", r"\texttt{low10}"), ("mean", r"\texttt{mean}"), ("min", r"\texttt{min}"), ("sc", "SC"),
          ("sum", r"\texttt{sum}")]
EDITS = [("swapped", "Other puzzle's solution"), ("fake final", "False last step"),
         ("made-up number", "Unavailable number"), ("answer only", "Answer only"),
         ("first step only", "First step only"), ("fake + self-praise", "False last step + praise"),
         ("prose padding", "Prose restatement"), ("redundant step", "Redundant true step")]
r = pd.read_csv("results.csv")
n = int(r.puzzles.iloc[0])
e = pd.read_csv("edits.csv")
sizes = e[e.edit == "gold"].n.value_counts().to_dict()
cell = lambda v: f"{v:.2f}"
body = []
for key, label in EDITS:
    vals = [cell(r[(r.judge == j) & (r.score == s) & (r.edit == key)].gold_wins.iloc[0]) for j, _ in JUDGES for s, _ in SCORES]
    body.append(f"{label} & " + " & ".join(vals) + r" \\")
K = len(SCORES)
heads = " & ".join(rf"\multicolumn{{{K}}}{{c}}{{{l}}}" for _, l in JUDGES)
rules = "".join(rf"\cmidrule(lr){{{2 + K * k}-{1 + K * (k + 1)}}}" for k in range(len(JUDGES)))
sub = " & ".join(l for _ in JUDGES for _, l in SCORES)
tex = rf"""% Generated by data/synthetic_countdown/make_synthetic_table.py (do not edit by hand: rerun it). Source: results.csv
% from Consistency_Synthetic_Gaming_Countdown (2026-11-04); narrative.md, "Synthetic gaming tests on Countdown".
\begin{{table}}[H]
\centering
\caption{{Synthetic gaming tests on Countdown (Llama-3.2-3B): share of puzzles in which the correct solution scores above its edited version.}}
\label{{tab:synthetic-countdown}}
\setlength{{\tabcolsep}}{{3pt}}
\begin{{adjustbox}}{{max width=\textwidth}}
\begin{{tabular}}{{l{'c' * K * len(JUDGES)}}}
\toprule
 & {heads} \\
{rules}
Edit & {sub} \\
\midrule
{chr(10).join(body)}
\bottomrule
\end{{tabular}}
\end{{adjustbox}}

\smallskip
\begin{{minipage}}{{\textwidth}}\footnotesize
{n} test puzzles ({sizes.get(4, 0)} with 4 numbers, {sizes.get(3, 0)} with 3). Each correct solution is a solver-written route (one step per line, then ``Answer: \ldots''), checked by the grader, and is scored against each edit of it under the judge prompt (neutral system prompt and the bare puzzle; the scored text is the solution, the answer and the end-of-turn token). Edits: another puzzle's correct solution; a route over the given numbers that misses the target, with the last step's result replaced by the target; a correct-looking route that uses an unavailable number; the answer line alone; the first step and the answer; the false last step followed by ``All steps check out.''; the sentence ``We need to reach $T$ using $a$, $b$, $c$ and $d$.'' before the steps; the true step ``$T * 1 = T$'' after them. The last four edits keep a correct answer. Ties count 1/2. \texttt{{mean}} / \texttt{{sum}}: mean / total token log-probability; \texttt{{low10}}: sum of the 10 lowest token log-probabilities; \texttt{{min}}: the lowest token log-probability; SC: self-certainty, the mean over scored positions of the KL divergence from the uniform distribution to the model's next-token distribution. Base model: Llama-3.2-3B-Instruct; SFT policy: GRPO's starting point, fine-tuned on solver-written judge-format solutions in the same style; corrupt DPO: the corrupted-reasoning judge.
\end{{minipage}}
\end{{table}}
"""
open("../../tables/tab_synthetic_countdown.tex", "w").write(tex)
print(tex[tex.index("\\midrule"):tex.index("\\bottomrule")])
