"""../../tables/tab_greedy_failures.tex (appendix): greedy accuracy, truncation and made-up numbers on the 200 + 200 test
puzzles for Llama-3.2-3B, start and the two runs of tab_format_vs_corrupt (150 steps). Sources (GRPO_Countdown_Llama, greedy
on the trainer's vLLM engine): start GRPO_DIR/eval_mixed_before_n200_max1024/eval_test{3,4}_before.json (the start of
[train]'s comparison), runs runs/<run>/eval_test{3,4}_after.json. Copied to greedy_failures.csv when Drive is mounted."""
import json
import os
from decimal import Decimal, ROUND_HALF_UP
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
TEX = os.path.join(HERE, "..", "..", "tables", "tab_greedy_failures.tex")
CSV = os.path.join(HERE, "greedy_failures.csv")
DRIVE = os.path.expanduser("~/Library/CloudStorage/GoogleDrive-alugarov@gmail.com/My Drive/Consistency/countdown")
L_DIR = f"{DRIVE}/grpo/Llama-3.2-3B-Instruct-countdown3000-ep1-lr0.0001-seed0-tr2-judge3000-mix3x3000-judge_dpo-start_sft"
RUNS = {"format": "grpo-format_only-mix3_0.5-expr-kl0.02-34-fmtw1-istt2-il-const",
        "judge": "grpo-sum-missmed-mix3_0.5-expr-kl0.02-corrupt_empty-cut-34-fmtw1-istt2-il-const"}
ARMS = ("start", "format", "judge")
METRICS = (("accuracy", "Accuracy"), ("accuracy_finished", r"\quad among finished"), ("truncated", "Truncated"),
           ("made_up_numbers", "Made-up numbers"))

if os.path.isdir(DRIVE):
    rows = []
    for n in (3, 4):
        files = {"start": f"{L_DIR}/eval_mixed_before_n200_max1024/eval_test{n}_before.json",
                 **{a: f"{L_DIR}/runs/{r}/eval_test{n}_after.json" for a, r in RUNS.items()}}
        for arm, f in files.items():
            d = json.load(open(f))
            assert d["n"] == 200, (f, d["n"])
            rows.append({"n_numbers": n, "arm": arm, **{m: d[m] for m, _ in METRICS}})
    pd.DataFrame(rows).to_csv(CSV, index=False)
res = pd.read_csv(CSV)
print(res.round(3).to_string(index=False))

num = lambda x: str(Decimal(repr(round(float(x), 9))).quantize(Decimal("0.001"), ROUND_HALF_UP))   # half up
v = lambda n, a, m: res[(res.n_numbers == n) & (res.arm == a)][m].iloc[0]
body = "\n".join(f"{lab} & " + " & ".join(num(v(n, a, m)) for n in (3, 4) for a in ARMS) + r" \\" for m, lab in METRICS)
tex = r"""% Generated by data/grpo_countdown_150/make_tab_greedy_failures.py (do not edit by hand: rerun it) -> greedy_failures.csv.
% Llama-3.2-3B, the runs of tab_format_vs_corrupt (countdown/grpo/<Llama mixed SFT>-judge_dpo-start_sft/runs/):
%   format only grpo-format_only-mix3_0.5-expr-kl0.02-34-fmtw1-istt2-il-const;
%   judge grpo-sum-missmed-mix3_0.5-expr-kl0.02-corrupt_empty-cut-34-fmtw1-istt2-il-const. Start: eval_mixed_before_n200_max1024.
% Previous version (older runs, with the solver-pair judge): tables/archive/tab_greedy_failures_solver_pair.tex.
\begin{table}[H]
\centering
\caption{Llama-3.2-3B, greedy decoding after 150 GRPO steps: accuracy, truncation and made-up numbers.}
\label{tab:greedy-failures}
\begin{threeparttable}
\setlength{\tabcolsep}{4pt}
\begin{tabular}{lcccccc}
\toprule
 & \multicolumn{3}{c}{3-number puzzles} & \multicolumn{3}{c}{4-number puzzles} \\
\cmidrule(lr){2-4}\cmidrule(lr){5-7}
 & Start & \makecell{Format\\ only} & \makecell{Format +\\ label-free judge} & Start & \makecell{Format\\ only} & \makecell{Format +\\ label-free judge} \\
\midrule
""" + body + r"""
\bottomrule
\end{tabular}
\begin{tablenotes}\footnotesize
\item The runs of Table~\ref{tab:format-vs-corrupt}, 200 test puzzles per size, one greedy completion each; start = the SFT model. Truncated: no answer within 1,024 tokens. Made-up numbers: share of answers using a number not among the given ones.
\end{tablenotes}
\end{threeparttable}
\end{table}
"""
open(TEX, "w").write(tex)
print("wrote", os.path.normpath(TEX))
