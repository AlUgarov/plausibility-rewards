"""judges_countdown.csv and ../../tables/tab_judges_countdown.tex: judges ranking correct over wrong completions of the
same puzzle by the sum score (total token log-probability of the scored span; the GRPO reward's reduction).
Llama-3.2-3B: context_scores.csv (2,560 GRPO training completions dumped from run mean-34 and its continuation cont100b
on the mixed SFT; one scoring pass for every judge, also behind tab_context_countdown).
Qwen3-0.6B: qwen/calibration_sum_missmed_S_grade_n200x8_t0.9_cap1024_seed0_scores.csv (Drive countdown/sft/<Qwen SFT>/
judge_corrupt_..._seed0/dpo_empty_b0.1_lr2e-05_ep2/): the SFT policy's own samples on the 400 grade puzzles x 8, T 0.9,
cap 1024, scored by the GRPO judge cell of GRPO_Countdown_Qwen (judge = the GRPO reward's judge, S = the SFT policy,
base = adapters off), solution + answer only; whole completion (after the GRPO prompt, SFT policy and base model):
qwen/context_scores_grade_n200x8_t0.9_cap1024_seed0.csv (Context_Score_Countdown_Qwen, the same scored rows).
Both spans are compared on the same completions: those with a solution to score. The mean-score version of the table: ../../tables/archive/tab_judges_countdown_mean.tex."""
import os
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
TEX = os.path.join(HERE, "..", "..", "tables", "tab_judges_countdown.tex")

llama = pd.read_csv(os.path.join(HERE, "context_scores.csv"))
llama["group"] = llama.step.astype(str) + "/" + llama.pid.astype(str)
llama["shorter"] = -llama.judge_sft_tokens
llama = llama[llama.judge_sft_sum.notna()].copy()   # completions with a solution to score (both spans on the same ones)
qwen = pd.read_csv(os.path.join(HERE, "qwen", "calibration_sum_missmed_S_grade_n200x8_t0.9_cap1024_seed0_scores.csv"))
assert (qwen.correct == qwen.correct_r).all()
qwen = qwen[qwen.scored].copy()          # completions with a solution to score (1,766 of 3,200)
qwen["group"] = qwen.n_numbers.astype(str) + "-" + qwen.puzzle.astype(str)
qw = pd.read_csv(os.path.join(HERE, "qwen", "context_scores_grade_n200x8_t0.9_cap1024_seed0.csv"))
assert len(qw) == len(qwen)
for k in ("n_numbers", "puzzle", "sample", "correct", "n_tokens"):
    assert (qw[k].values == qwen[k].values).all(), k
qwen["gen_full_sum"], qwen["gen_full_base_sum"] = qw.gen_full_sum.values, qw.gen_full_base_sum.values


def rates(df, col):
    """Within-puzzle share of (correct, wrong) pairs ranked correctly (ties 1/2), share of mixed puzzles in which every
    correct completion scores above every wrong one, number of mixed puzzles, number of pairs."""
    w = t = sep = mixed = 0
    for _, g in df.dropna(subset=[col]).groupby("group"):
        c, x = g.loc[g.correct, col].values, g.loc[~g.correct, col].values
        if len(c) and len(x):
            d = c[:, None] - x[None, :]
            w, t = w + (d > 0).sum() + 0.5 * (d == 0).sum(), t + d.size
            mixed, sep = mixed + 1, sep + (c.min() > x.max())
    return w / t, sep / mixed, mixed, t


# (judge, span, Llama column, Qwen column). Only rows with both models (no empty cells): the solver-made-errors judge
# exists for Llama only (judge_solver_sum of context_scores.csv).
ROWS = [("Base model policy", "whole completion", "gen_full_base_sum", "gen_full_base_sum"),
        ("Base model policy", "solution + answer", "judge_base_sum", "base_sum"),
        ("SFT policy", "whole completion", "gen_full_sum", "gen_full_sum"),
        ("SFT policy", "solution + answer", "judge_sft_sum", "S_sum"),
        ("Judge policy", "solution + answer", "judge_corrupt_sum", "judge_sum"),
        ("Shorter solution", "solution + answer", "shorter", "shorter")]
out = []
for judge, span, lc, qc in ROWS:
    for model, df, col in (("Llama-3.2-3B", llama, lc), ("Qwen3-0.6B", qwen, qc)):
        if col:
            p, s, m, n = rates(df, col)
            out.append(dict(judge=judge, span=span, model=model, column=col, pairs=p, groups_separated=s,
                            mixed_groups=m, n_pairs=n))
res = pd.DataFrame(out)
res.to_csv(os.path.join(HERE, "judges_countdown.csv"), index=False)
print(res.to_string(index=False))

cell = lambda judge, span, model: (lambda r: "-- & --" if r.empty else
                                   f"{r.pairs.iloc[0]:.3f} & {r.groups_separated.iloc[0]:.3f}")(
    res[(res.judge == judge) & (res.span == span) & (res.model == model)])
n = lambda model, span: res[(res.model == model) & (res.span == span)].iloc[0]
lines = [f"{j} & {s} & {cell(j, s, 'Llama-3.2-3B')} & {cell(j, s, 'Qwen3-0.6B')} \\\\" for j, s, _, _ in ROWS]
lines.insert(len(lines) - 1, "\\midrule")
ls, qs = n("Llama-3.2-3B", "solution + answer"), n("Qwen3-0.6B", "solution + answer")
