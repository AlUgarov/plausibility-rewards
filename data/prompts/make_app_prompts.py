"""../../tables/app_prompts.tex (appendix; needs \\usepackage{fvextra}): the prompts, written from code/countdown/prompts.py (the frozen strings the
SFT adapters, the judges and every GRPO / RFT run used) so the paper shows them byte for byte. Example puzzle: 25, 4, 7, 3
-> 96. The judge's scored text follows judge_data.judge_text (steps "a op b = c", one per line, then "Answer: ...")."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "code", "countdown"))
from prompts import countdown_prompt, judge_messages, NEUTRAL_SYSTEM_PROMPT   # noqa: E402

NUMBERS, TARGET = [25, 4, 7, 3], 96
STEPS, ANSWER = ["25 * 4 = 100", "100 - 7 = 93", "93 + 3 = 96"], "25 * 4 - 7 + 3"
policy = countdown_prompt(NUMBERS, TARGET)
judge = judge_messages(NUMBERS, TARGET)
assert [m["role"] for m in policy] == ["user"] and [m["role"] for m in judge] == ["system", "user"]
assert judge[0]["content"] == NEUTRAL_SYSTEM_PROMPT
scored = "\n".join(STEPS) + f"\nAnswer: {ANSWER}"
forced = "<reasoning>\n{kept part of the reasoning, empty for no reasoning}\n</reasoning>\n<solution>"   # + "\n"

def box(label, text):
    assert "\\end{Verbatim}" not in text
    return f"\\noindent\\textbf{{{label}}}\n\\begin{{Verbatim}}[frame=single, fontsize=\\small, breaklines, breakanywhere=false]\n{text}\n\\end{{Verbatim}}\n"

tex = r"""% Generated by data/prompts/make_app_prompts.py from code/countdown/prompts.py (do not edit by hand: rerun it).
\subsection*{Policy prompt}
""" + box("User", (policy[0]["content"])) + r"""
\subsection*{Judge prompt}
""" + box("System", (judge[0]["content"])) + box("User", (judge[1]["content"])) + \
    box("Assistant (scored)", scored) + r"""
\subsection*{Solution from corrupted reasoning}
The policy prompt above, then the assistant turn starts with:
""" + box("Assistant (forced start)", forced) + "\n" + r"""
\noindent Chat templates: Llama-3.2-3B's template starts every prompt with a system turn holding ``Cutting Knowledge Date: December 2023'' and ``Today Date: 26 Jul 2024'' (the date pinned), followed by the system prompt when there is one. Qwen3-0.6B runs with thinking off: with \texttt{enable\_thinking=False}, its template starts the assistant turn with an empty thinking block, \texttt{<think>} and \texttt{</think>} with a blank line between them.
"""
open(os.path.join(HERE, "..", "..", "tables", "app_prompts.tex"), "w").write(tex)
print(tex)
